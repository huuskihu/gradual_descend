section("13 · 综合：一个神经元的完整计算（就两行）")
# ======================================================================

rng = np.random.default_rng(0)
x = rng.random(784)                   # 假装有 784 个像素（一张 28x28 的图）
w = rng.normal(0, 0.1, size=784)      # 784 个权重
b = 0.0                               # 偏置

z = x @ w + b                         # 加权求和（@ 把 784 次乘法+加法一次做完）
a = sigmoid(z)                        # 激活函数
print(f"x 的形状 {x.shape}   w 的形状 {w.shape}")
print(f"加权求和 z = {z:.4f}")
print(f"激活后   a = {a:.4f}")
print("\n这就是神经网络里【一个神经元】的全部计算。")
print("所谓训练，就是不断调整 w 和 b 这两个数组，让输出越来越接近正确答案。")

