def sigmoid(z):
    """把任意数字压到 0~1 之间（神经网络里最常用的函数之一）
    def 定义函数，z 是参数，return 把结果交出去。
    下面这行三引号里的内容叫 docstring（文档字符串），是给人和 IDE 看的说明。"""
    return 1.0 / (1.0 + np.exp(-z))     # np.exp 是 e 的次方


print(f"sigmoid(0)   = {sigmoid(0)}")                  # 0.5
print(f"sigmoid(10)  = {sigmoid(10):.4f}")
print(f"sigmoid(-10) = {sigmoid(-10):.4f}")
# NumPy 的函数能对整个数组"逐元素"计算，不用写循环
print(f"一次算三个: {np.round(sigmoid(np.array([-1, 0, 1])), 3)}")


