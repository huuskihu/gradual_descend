section("5 · 类（class）与 self")
# ======================================================================
# 类 = 图纸；对象 = 照图纸造出来的房子。self 就是"我自己"。


class Neuron:
    """一个最简单的神经元：记住自己的权重，能对输入做加权求和"""

    def __init__(self, n_inputs):        # 造房子时自动执行（构造函数）
        self.n = n_inputs                # 存到自己身上，以后 self.n 就能取出来
        self.w = np.full(n_inputs, 0.5)  # 权重：造一个长度 n_inputs、全是 0.5 的数组
        self.b = 0.1                     # 偏置（基础分）

    def forward(self, x):                # 类里面的函数叫"方法"，第一个参数必须是 self
        return x @ self.w + self.b       # 用自己身上的权重去算


neu = Neuron(4)                          # 造一个能接收 4 个输入的神经元
print(f"它有几个输入: {neu.n}")
print(f"它的权重    : {neu.w}")
out = neu.forward(np.array([1.0, 2.0, 3.0, 4.0]))     # 调用方法
print(f"输入[1,2,3,4] 的输出: {out}")
print(f"手算验证: {1*0.5 + 2*0.5 + 3*0.5 + 4*0.5 + 0.1}    <- 一样，说明 @ 就是加权求和")


